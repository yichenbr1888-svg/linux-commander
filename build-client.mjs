// Builds client.js (the browser bundle) from src/client/widget.js and the
// locale dictionaries. Run with Node after editing the widget or locales:
//   node build-client.mjs
// The command library lives on the host only; editing src/commands.js or
// src/nl.js does NOT require a client rebuild (restart the host plugin).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
// The factory id MUST equal the package name: the host builds the client boot
// graph row from package.json "name", and the browser matches the registered
// factory to that row by id. A stale/hardcoded id makes the row fall back to a
// second bundle execution, which trips the duplicate-factory guard and crashes
// web boot. Derive it from the manifest so a rename can never drift again.
const pkgName = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name;
const zh = JSON.parse(readFileSync(join(root, 'locale', 'zh.json'), 'utf8'));
const en = JSON.parse(readFileSync(join(root, 'locale', 'en.json'), 'utf8'));
const widget = readFileSync(join(root, 'src', 'client', 'widget.js'), 'utf8');

const out = `// Generated by build-client.mjs — do not edit by hand.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkgName)},
  factory(require) {
    const React = require('react');
    const DICT_ZH = ${JSON.stringify(zh.ui)};
    const DICT_EN = ${JSON.stringify(en.ui)};
${widget}
    return {
      inject: ['slots', 'locale'],
      apply(ctx) {
        const t = ctx.locale.bind('linuxCommander');
        ctx.effect(() => {
          const disposers = [];
          for (const [loc, dict] of [['zh', DICT_ZH], ['en', DICT_EN]]) {
            try { disposers.push(ctx.locale.register('linuxCommander', loc, dict)); }
            catch (err) { console.error('linux-commander locale register:', err); }
          }
          return () => { for (const d of disposers) { try { d(); } catch { /* already gone */ } } };
        }, 'linux-commander.locale');
        const Widget = createWidget(React, ctx, t);
        ctx.effect(() => {
          const el = document.createElement('style');
          el.setAttribute('data-plugin', ${JSON.stringify(pkgName)});
          el.textContent = CSS;
          document.head.appendChild(el);
          return () => el.remove();
        }, 'linux-commander.styles');
        ctx.slots.inject('shell.overlay', () => ctx.slots.register({
          name: 'shell.overlay', id: 'linux-commander', order: 60,
        }, Widget));
      },
    };
  },
});
`;

writeFileSync(join(root, 'client.js'), out);
console.log(`client.js written: ${out.length} bytes`);